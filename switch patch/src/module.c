// The OOT-PC debug tools as a module the game loads itself (subsdk9), for a modded console or an emulator.
//
// The system's loader relocates this module and calls ootpc_module_init (DT_INIT) before the game starts. It finds
// main's base from main's exported nnMain, tells the game build by main's MOD0 header, checks that the build's IPS
// patch is in place (the marker and the branch at the frame site, tools/mkpatch.py) and writes the address of
// ootpc_frame to the slot the patch's stub reads. From then on the framework's per-frame update calls ootpc_frame on
// the game's own thread, once a frame, where the game's functions may be called.
//
// First tools, held L + R with a D-pad press:
//   Left   keep Link's position and facing
//   Right  put Link back there, through the game's own actor warp
//   Down   write Link's position to the log
// Every message goes to the debug log (OutputDebugString), which emulators show.

#include <stddef.h>
#include <stdint.h>

#include "builds.h"   // generated by tools/build.py from tools/builds.py
#include "horizon.h"

typedef struct {
    const char *name;
    int code;
    uint64_t mod0, nnmain, marker, site, site_word, slot, player_slot, warp_actor;
} Build;

static const Build builds[] = {OOTPC_BUILDS};

#define PLAYER_ACTOR_FIELD 0x480   // in the object at player_slot
#define ACTOR_NAME_FIELD 0x20      // char *: "Player"
#define ACTOR_AXES_FIELD 0x2f8     // the pose: three axis columns (x, y, z), 9 floats
#define ACTOR_POS_FIELD 0x31c      // then the position, 3 floats

// ---- the C library functions the compiler may call for struct copies and clears

__attribute__((used)) void *memcpy(void *dst, const void *src, size_t n) {
    uint8_t *d = dst;
    const uint8_t *s = src;
    while (n--) *d++ = *s++;
    return dst;
}

__attribute__((used)) void *memset(void *dst, int c, size_t n) {
    uint8_t *d = dst;
    while (n--) *d++ = (uint8_t)c;
    return dst;
}

__attribute__((used)) int memcmp(const void *a, const void *b, size_t n) {
    const uint8_t *x = a, *y = b;
    for (; n; n--, x++, y++)
        if (*x != *y) return *x - *y;
    return 0;
}

// ---- memory checks: a pointer the game holds is only followed once its memory is known to be mapped

static int mapped(uint64_t at, uint64_t n, uint32_t perm) {
    while (n) {
        MemInfo mi;
        if (svc_query_memory(&mi, at) || !mi.type || (mi.perm & perm) != perm) return 0;
        uint64_t left = mi.addr + mi.size - at;
        if (left >= n) return 1;
        at += left, n -= left;
    }
    return 1;
}

static uint64_t read_ptr(uint64_t at) { return at && mapped(at, 8, PERM_R) ? *(const uint64_t *)(uintptr_t)at : 0; }

// ---- the log

static char line[160];
static size_t line_len;

static void put(const char *s) {
    while (*s && line_len < sizeof line - 1) line[line_len++] = *s++;
}

static void put_hex(uint64_t v) {
    char b[19] = "0x";
    int n = 2;
    for (int i = 60; i >= 0; i -= 4)
        if (v >> i || i == 0 || n > 2) b[n++] = "0123456789abcdef"[v >> i & 15];
    b[n] = 0;
    put(b);
}

static void put_float(float f) {
    char b[24];
    int n = 0;
    if (!__builtin_isfinite(f)) return put("nan");
    if (f < 0) b[n++] = '-', f = -f;
    if (f > 1e9f) return put(n ? "-big" : "big");
    uint32_t cents = (uint32_t)(f * 100.0f + 0.5f), whole = cents / 100;
    char digits[12];
    int k = 0;
    do digits[k++] = (char)('0' + whole % 10), whole /= 10; while (whole);
    while (k) b[n++] = digits[--k];
    b[n++] = '.', b[n++] = (char)('0' + cents / 10 % 10), b[n++] = (char)('0' + cents % 10), b[n] = 0;
    put(b);
}

static void say_begin(void) { line_len = 0, put("[OOT-PC] "); }
static void say_end(void) { svc_output_debug_string(line, line_len); }
static void say(const char *s) { say_begin(), put(s), say_end(); }

// ---- the game

static const Build *game;
static uint64_t main_base;

static uint64_t player_actor(void) {
    uint64_t holder = read_ptr(main_base + game->player_slot);
    uint64_t actor = holder ? read_ptr(holder + PLAYER_ACTOR_FIELD) : 0;
    if (!actor || !mapped(actor, ACTOR_POS_FIELD + 12, PERM_R | PERM_W)) return 0;
    uint64_t name = read_ptr(actor + ACTOR_NAME_FIELD);
    if (!name || !mapped(name, 7, PERM_R) || memcmp((const void *)(uintptr_t)name, "Player", 7)) return 0;
    return actor;
}

static int finite_all(const float *f, int n) {
    for (int i = 0; i < n; i++)
        if (!__builtin_isfinite(f[i])) return 0;
    return 1;
}

typedef void (*WarpActor)(uint64_t actor, const float *pose, uint64_t zero);

static float kept_pos[3], kept_axes[9];
static int kept;

static void keep_position(void) {
    uint64_t actor = player_actor();
    if (!actor) return say("no player to keep the position of");
    float pos[3], axes[9];
    memcpy(pos, (const void *)(uintptr_t)(actor + ACTOR_POS_FIELD), sizeof pos);
    memcpy(axes, (const void *)(uintptr_t)(actor + ACTOR_AXES_FIELD), sizeof axes);
    if (!finite_all(pos, 3) || !finite_all(axes, 9)) return say("the player's pose is unreadable");
    memcpy(kept_pos, pos, sizeof pos), memcpy(kept_axes, axes, sizeof axes), kept = 1;
    say_begin(), put("kept position "), put_float(pos[0]), put(" "), put_float(pos[1]), put(" "), put_float(pos[2]);
    say_end();
}

// The game's warp takes a 3x4 row-major pose with the translation in the last column; the actor keeps its own as
// three columns, so each row takes one value of each column.
static void go_to_kept(void) {
    static _Alignas(16) float pose[12];
    if (!kept) return say("no position kept yet (L + R + D-pad left)");
    uint64_t actor = player_actor();
    if (!actor) return say("no player to move");
    const float *a = kept_axes, *p = kept_pos;
    const float m[12] = {a[0], a[3], a[6], p[0], a[1], a[4], a[7], p[1], a[2], a[5], a[8], p[2]};
    memcpy(pose, m, sizeof m);
    ((WarpActor)(uintptr_t)(main_base + game->warp_actor))(actor, pose, 0);
    say("back at the kept position");
}

static void report_position(void) {
    uint64_t actor = player_actor();
    if (!actor) return say("no player");
    const float *p = (const float *)(uintptr_t)(actor + ACTOR_POS_FIELD);
    say_begin(), put("Link at "), put_float(p[0]), put(" "), put_float(p[1]), put(" "), put_float(p[2]);
    put(" (actor "), put_hex(actor), put(")"), say_end();
}

// ---- input

typedef void (*GetStates)(NpadState *, int, const uint32_t *);

static uint64_t buttons_held(void) {
    static const uint32_t ids[] = {NPAD_NO1, NPAD_HANDHELD};
    static const GetStates styles[] = {
        _ZN2nn3hid13GetNpadStatesEPNS0_16NpadFullKeyStateEiRKj,
        _ZN2nn3hid13GetNpadStatesEPNS0_16NpadJoyDualStateEiRKj,
        _ZN2nn3hid13GetNpadStatesEPNS0_17NpadHandheldStateEiRKj,
    };
    uint64_t held = 0;
    for (size_t i = 0; i < sizeof ids / sizeof *ids; i++)
        for (size_t s = 0; s < sizeof styles / sizeof *styles; s++) {
            NpadState st[4];   // one is asked for; the rest is room to spare
            memset(st, 0, sizeof st);
            styles[s](st, 1, &ids[i]);
            if (st[0].attributes & 1) held |= st[0].buttons;
        }
    return held;
}

// ---- the frame hook and the start

static uint64_t frames, last_held;

void ootpc_frame(uint64_t framework) {
    (void)framework;
    if (!frames++) say("frame hook running");
    uint64_t held = buttons_held(), pressed = held & ~last_held;
    last_held = held;
    if ((held & (BTN_L | BTN_R)) != (BTN_L | BTN_R)) return;
    if (pressed & BTN_LEFT) keep_position();
    if (pressed & BTN_RIGHT) go_to_kept();
    if (pressed & BTN_DOWN) report_position();
}

static int patch_in_place(const Build *b, uint64_t base) {
    const uint8_t *m = (const uint8_t *)(uintptr_t)(base + b->marker);
    if (!mapped(base + b->marker, 16, PERM_R) || memcmp(m, "OOTPC-SW", 8)) return say("the IPS patch is missing"), 0;
    const uint32_t *w = (const uint32_t *)m;
    if (w[2] != 1 || w[3] != (uint32_t)b->code) return say("the IPS patch is for another build or format"), 0;
    if (*(const uint32_t *)(uintptr_t)(base + b->site) != (uint32_t)b->site_word)
        return say("the frame site does not hold the patch's branch"), 0;
    if (!mapped(base + b->slot, 8, PERM_R | PERM_W) || *(const uint64_t *)(uintptr_t)(base + b->slot))
        return say("the hook slot is not free"), 0;
    return 1;
}

__attribute__((used)) void ootpc_module_init(void) {
    for (size_t i = 0; i < sizeof builds / sizeof *builds; i++) {
        const Build *b = &builds[i];
        uint64_t base = (uint64_t)(uintptr_t)nnMain - b->nnmain;
        if ((base & 0xfff) || !mapped(base, 8, PERM_R) || !mapped(base + b->mod0, 4, PERM_R)) continue;
        if (*(const uint32_t *)(uintptr_t)(base + 4) != b->mod0) continue;   // main's own pointer to its MOD0
        if (memcmp((const void *)(uintptr_t)(base + b->mod0), "MOD0", 4)) continue;
        if (!patch_in_place(b, base)) return;
        game = b, main_base = base;
        *(uint64_t *)(uintptr_t)(base + b->slot) = (uint64_t)(uintptr_t)ootpc_frame;
        say_begin(), put("hook installed, game "), put(b->name), put(", main at "), put_hex(base), say_end();
        return;
    }
    say("not a game build this module knows; it stays off");
}
